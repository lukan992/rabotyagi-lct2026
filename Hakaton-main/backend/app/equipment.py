"""Справочник техники из ТЗ (п. 6.2) с формами слов для текстов предупреждений."""

from dataclasses import dataclass


@dataclass(frozen=True)
class Equipment:
    type: str
    name: str  # именительный ед.: «Самосвал»
    gen_sg: str  # родительный ед.: «не меньше 1 самосвала»
    gen_pl: str  # родительный мн.: «нет самосвалов», «не меньше 2 самосвалов»
    nom_pl: str  # именительный мн.: «где самосвалы»


_ROWS = [
    ("excavator", "Экскаватор", "экскаватора", "экскаваторов", "экскаваторы"),
    ("dump_truck", "Самосвал", "самосвала", "самосвалов", "самосвалы"),
    ("roller", "Каток", "катка", "катков", "катки"),
    ("manipulator", "Кран-манипулятор", "крана-манипулятора", "кранов-манипуляторов", "краны-манипуляторы"),
    ("mixer", "Бетоносмеситель", "бетоносмесителя", "бетоносмесителей", "бетоносмесители"),
    ("bulldozer", "Бульдозер", "бульдозера", "бульдозеров", "бульдозеры"),
    ("truck", "Грузовик", "грузовика", "грузовиков", "грузовики"),
    ("crane", "Автокран", "автокрана", "автокранов", "автокраны"),
]

EQUIPMENT: dict[str, Equipment] = {r[0]: Equipment(*r) for r in _ROWS}
EQUIPMENT_TYPES = tuple(EQUIPMENT)


def at_least(n: int, eq: Equipment) -> str:
    """«не меньше 1 экскаватора» / «не меньше 2 самосвалов»."""
    return f"не меньше {n} {eq.gen_sg if n == 1 else eq.gen_pl}"
