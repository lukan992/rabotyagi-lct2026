def build(key: str, stage_name: str, description: str, confirm: int, required, allowed, unexpected, position: int) -> Rule:  # noqa: ANN001
    rule = Rule(key=key, stage_name=stage_name, description=description, confirm_after=confirm, position=position)
    n = 0
    for kind, min_count, why, risk, *severity in required:
        rule.items.append(
            RuleItem(
                kind="required",
                equipment_type=kind,
                min_count=min_count,
                why=why,
                risk=risk,
                severity=severity[0] if severity else None,
                position=(n := n + 1),
            )
        )
    for kind in allowed:
        rule.items.append(RuleItem(kind="allowed", equipment_type=kind, position=(n := n + 1)))
    for kind, why, risk, *severity in unexpected:
        rule.items.append(
            RuleItem(
                kind="unexpected",
                equipment_type=kind,
                why=why,
                risk=risk,
                severity=severity[0] if severity else None,
                position=(n := n + 1),
            )
        )
    return rule


async def install(session: AsyncSession) -> int:
    """Добавить базовые правила, которых нет в базе (по ключу); изменённые администратором не трогаем. Сколько добавлено."""
    have = set(await session.scalars(select(Rule.key)))
    position = (await session.scalar(select(func.max(Rule.position)))) or 0
    added = 0
    for key, *fields in RULES:
        if key not in have:
            session.add(build(key, *fields, position=(position := position + 1)))
            added += 1
    await session.flush()
    return added


async def install_if_unused(session: AsyncSession) -> int:
    """Базовые правила — в базу, которой ещё никто не пользовался: ни сотрудников, ни объектов, ни правил."""
    for table in (User, Site, Rule):
        if await session.scalar(select(func.count()).select_from(table)):
            return 0
    return await install(session)
